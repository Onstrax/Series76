"""TraceabilityCloser and Release_Gate (Spec 6 Req 8.4-8.5, 9).

The mapping is DERIVED from the specs themselves: each requirement's
``Traces:`` line names user stories / QA scenarios / acceptance tests, and each
task's ``_Requirements:`` line names the requirements it implements. So an item
maps to (spec, task) when some requirement tracing it is implemented by some
task. Each item is then ``verified`` (evidence exists), ``pending`` (mapped,
no evidence yet), or ``gap`` (no spec / task) — ``pending`` and ``gap`` are
mutually exclusive by construction.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path

SPECS: tuple[str, ...] = (
    "data-and-ingestion",
    "domain-and-tools",
    "backend-api-auth-jobs-crypto",
    "agent-orchestration-response",
    "android-app",
    "evaluation-and-reproducibility",
)


def obligations() -> list[str]:
    """The integral obligation set (Req 9.1-9.3)."""

    items = [f"US-{i:03d}" for i in range(1, 35)] + ["US-035", "US-036"]
    items += [f"QA-{i:02d}" for i in range(1, 16)]
    items += ["F1 §6", "F1 §11"]
    items += [f"F3-AT{i:02d}" for i in range(1, 13)]
    items += [f"F4-AT{i:02d}" for i in range(1, 20)]
    items += [f"F5-OFF-{i:02d}" for i in range(1, 8)]
    items += [f"AT-{i:02d}" for i in range(1, 19)]
    return items


_ITEM = re.compile(
    r"(US-\d{3}|QA-\d{2}|F3-AT\d{2}|F4-AT\d{2}|F5-OFF-\d{2}|(?<![\w-])AT-\d{2}|F1 §\d+)"
)
_PREFIXES = r"US-|QA-|F3-AT|F4-AT|F5-OFF-|AT-"
_RANGE = re.compile(rf"({_PREFIXES})(\d+)\s*\.\.\s*(?:{_PREFIXES})?(\d+)")


def _expand(text: str) -> set[str]:
    found = set(_ITEM.findall(text))
    for prefix, a, b in _RANGE.findall(text):
        width = len(a)
        for n in range(int(a), int(b) + 1):
            found.add(f"{prefix}{n:0{width}d}")
    return found


def parse_requirement_traces(requirements_md: str) -> dict[int, set[str]]:
    """Requirement number -> items it traces (from its heading block)."""

    out: dict[int, set[str]] = {}
    blocks = re.split(r"^### Requirement (\d+):", requirements_md, flags=re.M)
    for i in range(1, len(blocks) - 1, 2):
        number = int(blocks[i])
        body = blocks[i + 1].split("#### Acceptance Criteria")[0]
        out[number] = _expand(body)
    return out


def parse_task_requirements(tasks_md: str) -> dict[str, set[int]]:
    """Task id -> requirement numbers it implements."""

    out: dict[str, set[int]] = {}
    current: str | None = None
    for line in tasks_md.splitlines():
        m = re.match(r"^\s*- \[[ x]\]\*?\s+(\d+(?:\.\d+)?)\.?\s", line)
        if m:
            current = m.group(1)
            continue
        r = re.search(r"^\s*-?\s*_?Requirements:\s*(.+?)_?\s*$", line)
        if r and current is not None:
            nums = {int(x.split(".")[0]) for x in re.findall(r"\b(\d+)(?:\.\d+)?\b", r.group(1))}
            out.setdefault(current, set()).update(nums)
    return out


class Status(str, Enum):
    VERIFIED = "verified"
    PENDING = "pending"
    GAP = "gap"


@dataclass(frozen=True, slots=True)
class TraceabilityRow:
    item_id: str
    specs: tuple[str, ...]
    tasks: tuple[str, ...]
    evidence_ref: str | None
    status: Status

    def __post_init__(self) -> None:
        mapped = bool(self.specs) and bool(self.tasks)
        if self.status is Status.GAP and mapped:
            raise ValueError("a mapped item is pending or verified, never gap")
        if self.status is Status.VERIFIED and self.evidence_ref is None:
            raise ValueError("verified requires an Evidence_Record reference")
        if self.status is Status.PENDING and not mapped:
            raise ValueError("pending requires an implementing spec and task")
        if self.status is Status.PENDING and self.evidence_ref is not None:
            raise ValueError("an evidenced item is verified, not pending")


def classify(specs: tuple[str, ...], tasks: tuple[str, ...], evidence_ref: str | None) -> Status:
    """verified / pending / gap — pending and gap are mutually exclusive."""

    if not specs or not tasks:
        return Status.GAP
    return Status.VERIFIED if evidence_ref else Status.PENDING


@dataclass
class TraceabilityArtifact:
    rows: list[TraceabilityRow] = field(default_factory=list)

    def by_status(self, status: Status) -> list[TraceabilityRow]:
        return [r for r in self.rows if r.status is status]

    def to_markdown(self) -> str:
        lines = [
            "# Integral cross-spec traceability (Specs 1-6)",
            "",
            "Generated by `python -m series76_eval traceability` from the `Traces:` lines of",
            "every requirement and the `Requirements:` lines of every task. `verified` needs a",
            "persisted Evidence_Record; `pending` = mapped but not yet evidenced; `gap` = no",
            "implementing spec/task.",
            "",
            f"Totals: {len(self.by_status(Status.VERIFIED))} verified, "
            f"{len(self.by_status(Status.PENDING))} pending, {len(self.by_status(Status.GAP))} gap "
            f"(of {len(self.rows)}).",
            "",
            "| Item | Specs | Tasks | Evidence | Status |",
            "|---|---|---|---|---|",
        ]
        for r in self.rows:
            tasks = ", ".join(r.tasks[:8]) + (" …" if len(r.tasks) > 8 else "")
            lines.append(
                f"| {r.item_id} | {', '.join(r.specs) or '—'} | {tasks or '—'} | "
                f"{r.evidence_ref or '—'} | {r.status.value} |"
            )
        return "\n".join(lines) + "\n"


def build_artifact(
    specs_root: Path,
    evidence_for: dict[str, str] | None = None,
    items: list[str] | None = None,
) -> TraceabilityArtifact:
    """Derive the integral map from the six specs (Req 9.1-9.6)."""

    evidence_for = evidence_for or {}
    mapping: dict[str, tuple[set[str], set[str]]] = {}
    for spec in SPECS:
        folder = specs_root / spec
        traces = parse_requirement_traces((folder / "requirements.md").read_text(encoding="utf-8"))
        tasks = parse_task_requirements((folder / "tasks.md").read_text(encoding="utf-8"))
        for req, traced in traces.items():
            implementing = sorted(t for t, reqs in tasks.items() if req in reqs)
            if not implementing:
                continue
            for item in traced:
                specs, task_ids = mapping.setdefault(item, (set(), set()))
                specs.add(spec)
                task_ids.update(f"{spec}#{t}" for t in implementing)
    rows = []
    for item in items or obligations():
        specs, task_ids = mapping.get(item, (set(), set()))
        spec_t = tuple(s for s in SPECS if s in specs)
        task_t = tuple(sorted(task_ids))
        ev = evidence_for.get(item)
        rows.append(TraceabilityRow(item, spec_t, task_t, ev, classify(spec_t, task_t, ev)))
    return TraceabilityArtifact(rows)


class CriticalCategory(str, Enum):
    NUMERIC_INTEGRITY = "numeric_integrity"
    AUTHORIZATION = "authorization"
    ISOLATION = "isolation"
    MANDATORY_ENCRYPTION = "mandatory_encryption"
    PERSISTENCE_NO_RESURRECTION = "persistence_no_resurrection"
    CONVERSATION_CONTRACT = "conversation_contract"


@dataclass(frozen=True, slots=True)
class Defect:
    category: CriticalCategory
    scope: str


@dataclass(frozen=True, slots=True)
class ReleaseGateRecord:
    recorded_defects: tuple[Defect, ...]

    def state(self, category: CriticalCategory) -> str:
        return "defect" if any(d.category is category for d in self.recorded_defects) else "clear"

    @property
    def releasable(self) -> bool:
        """Releasable iff zero known critical defects (Req 8.4, 8.5)."""
        return not self.recorded_defects
