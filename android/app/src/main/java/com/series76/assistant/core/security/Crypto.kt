package com.series76.assistant.core.security

import java.security.GeneralSecurityException
import java.security.SecureRandom
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

/** The required key is missing or the Keystore refused it: fail closed. */
class KeyUnavailableException(message: String, cause: Throwable? = null) : Exception(message, cause)

/** Authenticated encryption of small payloads with associated data. */
interface CipherBox {
    /** Returns `iv || ciphertext+tag`. */
    fun encrypt(plain: ByteArray, aad: ByteArray): ByteArray

    /** Throws [KeyUnavailableException] if the key is gone or the blob is not authentic. */
    fun decrypt(blob: ByteArray, aad: ByteArray): ByteArray
}

/**
 * AES-256-GCM with a 96-bit IV generated by the provider and a 128-bit tag.
 * The key comes from [keyProvider]: an Android Keystore key in the app (the
 * key material never leaves the Keystore) or a JVM key in unit tests.
 */
class AesGcmCipherBox(private val keyProvider: () -> SecretKey?) : CipherBox {

    override fun encrypt(plain: ByteArray, aad: ByteArray): ByteArray {
        val key = keyProvider() ?: throw KeyUnavailableException("encryption key unavailable")
        return try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, key)
            cipher.updateAAD(aad)
            val ct = cipher.doFinal(plain)
            val iv = cipher.iv
            check(iv.size == IV_BYTES) { "unexpected IV length" }
            iv + ct
        } catch (e: GeneralSecurityException) {
            throw KeyUnavailableException("encryption failed", e)
        }
    }

    override fun decrypt(blob: ByteArray, aad: ByteArray): ByteArray {
        val key = keyProvider() ?: throw KeyUnavailableException("decryption key unavailable")
        if (blob.size <= IV_BYTES) throw KeyUnavailableException("malformed ciphertext")
        return try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(
                Cipher.DECRYPT_MODE,
                key,
                GCMParameterSpec(TAG_BITS, blob.copyOfRange(0, IV_BYTES)),
            )
            cipher.updateAAD(aad)
            cipher.doFinal(blob.copyOfRange(IV_BYTES, blob.size))
        } catch (e: GeneralSecurityException) {
            throw KeyUnavailableException("decryption failed", e)
        }
    }

    companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val IV_BYTES = 12
        const val TAG_BITS = 128

        /** A raw 32-byte key (used for per-user data keys unwrapped in memory). */
        fun ofRawKey(raw: ByteArray): AesGcmCipherBox {
            val key = SecretKeySpec(raw, "AES")
            return AesGcmCipherBox { key }
        }

        fun randomKeyBytes(random: SecureRandom = SecureRandom()): ByteArray =
            ByteArray(32).also(random::nextBytes)
    }
}

/** A small persistent byte store (SharedPreferences in the app, a map in tests). */
interface BlobStore {
    fun put(key: String, value: ByteArray)
    fun get(key: String): ByteArray?
    fun remove(key: String)
    fun keys(): Set<String>
}

class InMemoryBlobStore : BlobStore {
    private val map = LinkedHashMap<String, ByteArray>()
    override fun put(key: String, value: ByteArray) { map[key] = value.copyOf() }
    override fun get(key: String): ByteArray? = map[key]?.copyOf()
    override fun remove(key: String) { map.remove(key) }
    override fun keys(): Set<String> = map.keys.toSet()
    /** Every stored byte, for plaintext-leak scans in tests. */
    fun allBytes(): List<ByteArray> = map.values.map { it.copyOf() }
}
